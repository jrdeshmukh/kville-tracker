// K-Ville Tracker service worker: shows push notifications and opens the app on tap.
self.addEventListener("push", (event) => {
  let data = { title: "K-Ville Tracker", body: "", url: "/" };
  try {
    data = { ...data, ...event.data.json() };
  } catch {}
  event.waitUntil(
    self.registration.showNotification(data.title, {
      body: data.body,
      icon: "/icon.svg",
      badge: "/icon.svg",
      data: { url: data.url },
      vibrate: data.title.includes("TENT CHECK") ? [300, 100, 300, 100, 300] : [150],
      requireInteraction: data.title.includes("TENT CHECK"),
    }),
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = event.notification.data?.url || "/";
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((list) => {
      for (const c of list) if ("focus" in c) { c.navigate(url); return c.focus(); }
      return self.clients.openWindow(url);
    }),
  );
});
